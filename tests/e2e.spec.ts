test('CSV와 Excel 다운로드에 필터 결과와 전체 업무 시트가 포함된다', async ({ page }) => {
  await ready(page)
  await page.getByLabel('스타일 검색', { exact: true }).fill('BO42FYJK0101')
  await page.getByRole('button', { name: '다운로드', exact: true }).click()
  let pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'CSV 파일 (.csv)', exact: true }).click()
  const csv = await pending
  expect(csv.suggestedFilename()).toMatch(/\.csv$/)
  const contents = await readFile((await csv.path())!, 'utf8')
  expect(contents).toContain('BO42FYJK0101')
  expect(contents).not.toContain('BO42FYHD0102')
  expect(contents).toContain('실 출고 수량')
  await page.getByRole('button', { name: '다운로드', exact: true }).click()
  pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Excel 통합 문서 (.xlsx)', exact: true }).click()
  const xlsx = await pending
  expect(xlsx.suggestedFilename()).toMatch(/\.xlsx$/)
  const workbook = new ExcelJS.Workbook()
  await workbook.xlsx.readFile((await xlsx.path())!)
  expect(workbook.worksheets.map(sheet => sheet.name)).toEqual(['스타일', '샘플 이력', '메인 생산', '변경 이력', '협업 코멘트', '첨부파일 목록'])
  expect(workbook.getWorksheet('스타일')?.rowCount).toBe(2)
  expect(workbook.getWorksheet('샘플 이력')?.rowCount).toBe(3)
  expect(workbook.getWorksheet('메인 생산')?.rowCount).toBe(3)
  expect(workbook.getWorksheet('메인 생산')?.getRow(1).values).toContain('실 입고 XL')
})

